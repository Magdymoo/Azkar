/* أذكاري — home.js (v2.0): رسالة الصفحة الرئيسية كدالة نقية قابلة للاختبار.
   homeMessage({phase,mD,eD,sD,q,gender,lang}) → {tx,sub,buttons:[[label,key]],pend,remaining}
   phase: m صباح · d ظهر · e مساء · n ليل (من AZ.day.phase) — والإتمام على «اليوم الأذكاري». */
(function (w) {
  'use strict';
  var AZ = w.AZ = w.AZ || {};
  function homeMessage(o) {
    var ph = o.phase, mD = !!o.mD, eD = !!o.eD, sD = !!o.sD, q = !!o.q, f = o.gender === 'f', tx = '', sub = '', B = [];
    var g = function (m, fe) { return f ? fe : m; };
    if (ph === 'm') {
      if (mD) tx = 'بفضل الله أتممت أذكار الصباح 🤍\nنسأل الله أن يحفظك ويحفظ يومك.';
      else { tx = g('ابدأ', 'ابدئي') + ' يومك بأذكار الصباح، وقتها الآن.'; B.push(['أذكار الصباح', 'm']); }
    } else if (ph === 'd') {
      if (!mD) { tx = 'ما زال بإمكانك قراءة أذكار الصباح، فلا تفوّتها.'; B.push(['أذكار الصباح', 'm']); }
      else tx = 'أتممت أذكار الصباح، حفظك الله. وقت أذكار المساء بعد العصر بإذن الله.';
    } else if (ph === 'e') {
      if (eD) tx = 'بفضل الله أتممت أذكار المساء 🤍\nنسأل الله أن يحفظك حتى الصباح.';
      else { tx = 'حان وقت أذكار المساء.'; B.push(['أذكار المساء', 'e']); if (!mD) sub = 'لم تقرأ أذكار الصباح بعد، ويمكنك قراءتها أيضاً.'; }
    } else {                                                        // الليل: الجدول الرباعي (المساء × النوم)
      if (!eD && !sD) { tx = 'لم تقرأ أذكار المساء بعد، ' + g('اقرأها', 'اقرئيها') + ' قبل أن ' + g('تنام', 'تنامي') + '.'; B.push(['أذكار المساء', 'e']); }
      else if (!eD && sD) { tx = g('أتممت أذكار النوم، بارك الله فيك، ويمكنك قراءة أذكار المساء أيضًا.', 'أتممتِ أذكار النوم، بارك الله فيكِ، ويمكنكِ قراءة أذكار المساء أيضًا.'); B.push(['أذكار المساء', 'e']); }
      else if (eD && !sD) { tx = 'ختمت يومك بأذكار المساء، حفظك الله. لا ' + g('تنسَ', 'تنسَيْ') + ' أذكار النوم.'; B.push(['أذكار قبل النوم', 's']); }
      else tx = g('ختمت يومك بأذكار المساء، حفظك الله. ومنَّ الله عليك فقرأت أذكار قبل النوم، بارك الله فيك.', 'ختمت يومك بأذكار المساء، حفظك الله. ومنَّ الله عليكِ فقرأتِ أذكار قبل النوم، بارك الله فيكِ.');
    }
    if (!q && ph !== 'n') { sub += (sub ? ' ' : '') + 'ورد القرآن اليوم لم يُقرأ بعد.'; B.push(['ورد القرآن', 'q']); }   // حتى دخول العشاء
    var adhPend = ((ph === 'm' || ph === 'd') && !mD) || ((ph === 'e' || ph === 'n') && !eD) || (ph === 'n' && eD && !sD);
    var pend = adhPend || (ph !== 'n' && !q);
    var remaining = (mD ? 0 : 1) + (eD ? 0 : 1) + (q ? 0 : 1) + (ph === 'n' && !sD ? 1 : 0);
    return { tx: tx, sub: sub, buttons: B, pend: pend, remaining: remaining };
  }
  AZ.homeMessage = homeMessage;
})(window);
